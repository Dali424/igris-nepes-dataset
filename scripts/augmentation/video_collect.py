#!/usr/bin/env python3
"""Photometric derivatives of a complete or explicitly selected LeRobotv3 dataset.

--preflight validates the source and writes nothing. --execute creates the selected final
photometric datasets and a durable state.json. --resume requires the same plan;
published outputs and per-video checkpoints are revalidated before reuse.
The caller may hold the native/global and collection locks. This CPU-only worker
uses only its own .video.lock and never launches Isaac or changes source files.
"""
from __future__ import annotations
import argparse
from concurrent.futures import ThreadPoolExecutor,wait,FIRST_COMPLETED
from datetime import datetime,timezone
import fcntl
import os
from pathlib import Path
import shutil
import signal
import sys
import time
from uuid import uuid4
import video_common as common
from video_common import engine


def now():return datetime.now(timezone.utc).isoformat()

def process_video(source,work,job,recipe,minimum_delta):
    target=work/job['path'];target.parent.mkdir(parents=True,exist_ok=True)
    # A file without a committed checkpoint is an interrupted private derivative,
    # never an original or already-published dataset. Re-encode it from source.
    if target.exists():target.unlink()
    temporary=target.with_name('.'+target.stem+'.encoding-'+uuid4().hex+'.mp4')
    try:
        statistics,audit=engine.transform_video(source/job['path'],temporary,job['shape'],job['frames'],recipe)
        common.require(audit['source_sha256']==job['source_sha256'],'Source video changed during encoding')
        direction=1 if recipe['name']=='visible_brighter_v2' else -1
        common.require(direction*audit['mean_luma_delta']>=minimum_delta,f'Insufficient/wrong-direction mean brightness change for {job["path"]}: {audit["mean_luma_delta"]:+.6f}')
        with temporary.open('rb') as stream:os.fsync(stream.fileno())
        temporary.replace(target)
        record={'schema':'nepes_video_job_checkpoint_v1','job':job,'recipe_sha256':common.digest(recipe),'statistics':statistics,'audit':audit}
        common.validate_job(source,work,job,recipe,record,minimum_delta)
        return record
    finally:temporary.unlink(missing_ok=True)

def process_preset(source,output,plan,layout,preset,workers,stop,progress):
    final=output/preset
    if final.exists():
        result=common.verify_final(source,final,plan,preset,layout);progress(preset,'complete',len(layout['jobs']),result);return result
    work=output/('.'+preset+'.work');work.mkdir(exist_ok=True)
    # Only names generated by this worker are removed after a hard interruption.
    for path in work.rglob('.*.encoding-*.mp4'):
        common.require(path.is_file() and not path.is_symlink(),'Invalid private encoding temporary');path.unlink()
    for relative in ('meta/info.json','meta/stats.json',common.PROVENANCE,common.AUDIT):
        destination=work/relative
        for path in destination.parent.glob('.'+destination.name+'.*'):
            common.require(path.is_file() and not path.is_symlink(),'Invalid private metadata temporary');path.unlink()
    checkpoints=output/'checkpoints'/preset;checkpoints.mkdir(parents=True,exist_ok=True)
    recipe=plan['presets'][preset];records={};pending=[]
    for job in layout['jobs']:
        path=checkpoints/f'video_{job["index"]:06d}.json'
        if path.exists():
            record=common.read(path);common.validate_job(source,work,job,recipe,record,plan['minimum_absolute_mean_luma_delta']);records[job['index']]=record
        else:pending.append(job)
    progress(preset,'encoding',len(records))
    with ThreadPoolExecutor(max_workers=workers) as pool:
        running={};cursor=0
        while cursor<len(pending) or running:
            if (output/'STOP').exists():stop[0]=True
            while not stop[0] and cursor<len(pending) and len(running)<workers:
                job=pending[cursor];cursor+=1;future=pool.submit(process_video,source,work,job,recipe,plan['minimum_absolute_mean_luma_delta']);running[future]=job
            if not running:break
            done,_=wait(running,timeout=1,return_when=FIRST_COMPLETED)
            for future in done:
                job=running.pop(future);record=future.result()
                common.atomic_json(checkpoints/f'video_{job["index"]:06d}.json',record);records[job['index']]=record
                progress(preset,'encoding',len(records))
            # Cooperative stop finishes at most the currently encoding videos;
            # complete checkpoints remain reusable and no new videos are started.
    if stop[0]:raise InterruptedError('Video augmentation stopped at a per-video boundary')
    common.require(len(records)==len(layout['jobs']),'Incomplete video transformation')
    ordered=[records[job['index']] for job in layout['jobs']]
    progress(preset,'metadata',len(records))
    preserved,provenance=common.write_metadata(source,work,layout,plan,preset,ordered)
    common.require(common.sha(source/engine.RECEIPT)==plan['source_receipt_sha256'],'Original receipt changed during augmentation')
    common.check_inventory(source,plan['source_files'])
    audit={'schema':'nepes_seeded_video_dataset_audit_v1','verified':True,'preset':preset,'plan_sha256':common.digest(plan),'source_receipt_sha256':plan['source_receipt_sha256'],'episodes':plan['expected_episodes'],'frames':plan['total_frames'],'video_records':ordered,'preserved_parquet':preserved,'action_state_timing_tasks_bit_exact':True,'modified_numeric_columns':[common.FLAG],'independent_physics_execution':False,'physical_success_revalidated':False,'original_success_labels_inherited':True,'four_cameras_full_decoded_and_frame_counts_preserved':True,'image_stats_recomputed_from_decoded_output':True,'files':engine.inventory(work,exclude=(common.AUDIT,)),'created_utc':now()}
    common.atomic_json(work/common.AUDIT,audit)
    # Validate the staged dataset exactly as a published dataset before atomic publication.
    common.verify_final(source,work,plan,preset,layout)
    common.require(not final.exists(),'Final dataset appeared; refusing overwrite')
    work.rename(final)
    directory=os.open(output,os.O_DIRECTORY)
    try:os.fsync(directory)
    finally:os.close(directory)
    result=common.verify_final(source,final,plan,preset,layout)
    progress(preset,'complete',len(records),result);return result

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--expected-episodes',type=int)
    parser.add_argument('--presets',nargs='+',choices=common.PRESETS,default=[common.PRESETS[0]])
    parser.add_argument('--workers',type=int,default=2)
    parser.add_argument('--resume',action='store_true')
    mode=parser.add_mutually_exclusive_group(required=True);mode.add_argument('--preflight',action='store_true');mode.add_argument('--execute',action='store_true');mode.add_argument('--verify-complete',action='store_true')
    args=parser.parse_args();source=args.source.resolve(strict=True);output=args.output.resolve()
    common.require(1<=args.workers<=4,'Use between1 and4 CPU video workers')
    common.require(not output.is_relative_to(source) and not source.is_relative_to(output),'Source/output directories must not overlap')
    plan,layout,receipt=common.source_plan(source,args.expected_episodes,tuple(args.presets))
    if args.preflight:
        print(__import__('json').dumps({'ready':True,'writes_performed':False,'plan':plan,'videos_per_preset':len(layout['jobs']),'derived_episodes':len(plan['presets'])*plan['expected_episodes']},indent=2));return 0
    if args.resume or args.verify_complete:
        common.require((output/'state.json').is_file(),'No existing video state to resume/verify')
    else:
        common.require(not output.exists(),'Output already exists; use --resume with the same source/tools')
        output.mkdir(parents=True)
    with (output/'.video.lock').open('a') as lock:
        fcntl.flock(lock.fileno(),fcntl.LOCK_EX|fcntl.LOCK_NB)
        if args.resume or args.verify_complete:
            state=common.read(output/'state.json');common.require(state['plan']==plan,'Frozen source/recipe/tool plan differs; refusing mixed augmentation output')
        else:state={'schema':'nepes_seeded_video_batch_v1','created_utc':now(),'status':'prepared','plan':plan,'presets':{}}
        if args.resume and (output/'STOP').exists():
            (output/'STOP').rename(output/f'STOP_resumed_{time.time_ns()}')
        stop=[False]
        for sig in (signal.SIGINT,signal.SIGTERM):signal.signal(sig,lambda *_:stop.__setitem__(0,True))
        def progress(preset,status,count,result=None):
            common.require(common.tool_hashes()==plan['tool_sha256'],'Frozen video worker changed during execution')
            state.update(updated_utc=now(),pid=os.getpid(),status='running')
            state['presets'][preset]={'status':status,'completed_videos':count,'total_videos':len(layout['jobs'])}
            if result:state['presets'][preset]['result']=result
            common.atomic_json(output/'state.json',state)
            print(f'{preset}: {status} {count}/{len(layout["jobs"])} videos',flush=True)
        try:
            if args.verify_complete:
                results=[common.verify_final(source,output/preset,plan,preset,layout) for preset in plan['presets']]
            else:
                results=[]
                for preset in plan['presets']:
                    if stop[0] or (output/'STOP').exists():raise InterruptedError('STOP requested')
                    results.append(process_preset(source,output,plan,layout,preset,args.workers,stop,progress))
            common.check_inventory(source,receipt['files'])
            common.require(common.sha(source/engine.RECEIPT)==plan['source_receipt_sha256'],'Parent receipt changed')
            state.update(status='complete',updated_utc=now(),completed_utc=now(),results=results,total_augmented_episodes=len(plan['presets'])*plan['expected_episodes'])
            common.atomic_json(output/'state.json',state)
            print(__import__('json').dumps({'status':'complete','datasets':results,'augmented_episodes':len(plan['presets'])*plan['expected_episodes'],'independent_physics_executions':0},indent=2));return 0
        except BaseException as exc:
            state.update(status='stopped' if isinstance(exc,InterruptedError) else 'needs_review',error=f'{type(exc).__name__}: {exc}',updated_utc=now())
            common.atomic_json(output/'state.json',state)
            if isinstance(exc,InterruptedError):return 130
            raise

if __name__=='__main__':
    try:raise SystemExit(main())
    except (OSError,ValueError,RuntimeError,KeyError) as exc:raise SystemExit(f'Video augmentation stopped: {exc}') from exc
